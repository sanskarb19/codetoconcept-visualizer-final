const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {execFileSync}=require('node:child_process');
const cases=JSON.parse(execFileSync('python',['tests/storyboard_cases.py'],{encoding:'utf8',maxBuffer:5*1024*1024}));
const ctx={window:{}};
for(const name of ['learning','storyboard','tutor','guided'])vm.runInNewContext(fs.readFileSync(`frontend/js/${name}.js`,'utf8'),ctx);
const G=ctx.window.GuidedLesson;
const steps=name=>ctx.window.Storyboard.build(cases[name].events,cases[name].statements,cases[name].source_code);
const addition=steps('addition'),step=addition[2];
const state={teachingSteps:addition,lessonIndex:2};
G.sync(state,step);
let view=G.view(step,state.study);
assert.equal(view.hidden,true);
assert.match(view.html,/READ x/);assert.match(view.html,/READ y/);
assert.doesNotMatch(view.html,/>30</,'the read stage must not reveal the answer');
assert.equal(G.advance(state),true);
view=G.view(step,state.study);assert.equal(view.hidden,true);
assert.match(view.html,/10 \+ 20/);assert.match(view.html,/EXPRESSION MAP/);
assert.match(view.html,/Explain the symbols/);
assert.equal(G.advance(state),true);assert.equal(G.view(step,state.study).hidden,false);
assert.equal(G.advance(state),false);
G.sync(state,addition[3]);assert.equal(state.study.phase,0,'a new instruction starts with inputs');
const quiz=G.task(step);assert.equal(quiz.answer,30);
assert.equal(G.grade(quiz,'30').correct,true);
assert.equal(G.grade(quiz,'29').correct,false);
assert.match(G.grade(quiz,'').message,/Enter a prediction/);
G.sync(state,step);G.handle({dataset:{studyAction:'mode',mode:'predict'}},state);
assert.equal(G.view(step,state.study).hidden,true);
state.study.answer='29';G.handle({dataset:{studyAction:'check'}},state);
assert.equal(state.study.revealed,true);assert.equal(state.study.feedback.correct,false);
assert.match(G.view(step,state.study).html,/recorded answer is 30/);
const branch=steps('decision').find(s=>s.meta.kind==='if');
const map=G.programMap({execution:cases.decision,teachingSteps:steps('decision'),lessonIndex:0});
assert.match(map,/Choose a branch/);assert.match(map,/Not reached/);
assert.equal(G.grade(G.task(branch),'NO').correct,true);
assert.equal(G.grade(G.task(branch),'YES').correct,false);
const matrix=steps('matlab_powers')[2];assert.equal(G.task(matrix).answer,2);
const loop=steps('loop');const loopState={teachingSteps:loop,lessonIndex:loop.length-1,historyName:'total'};
const history=G.history(loopState);assert.match(history,/value-trend/);assert.match(history,/data-history-index/);
const nested=steps('nested');const inner=nested.findIndex(s=>s.event.function==='double'&&s.meta.kind==='return');
const call=nested.find(s=>s.kind==='enter');assert.equal(G.inputs(call)[0].name,'n');assert.equal(G.inputs(call)[0].value.value,3);
const scoped=G.history({teachingSteps:nested,lessonIndex:inner});assert.doesNotMatch(scoped,/<strong>x<\/strong>/,'caller values must not be presented as local changes');
const injection={...step,before:{x:{__type__:'str',value:'<img onerror=evil>'}},meta:{expression:{kind:'name',name:'x'},targets:['total']}};
assert.doesNotMatch(G.view(injection,{mode:'guided',phase:0}).html,/<img/);
console.log('Passed: staged reveal, expression map, prediction grading, input validation, branch questions, matrix questions, scoped history, numeric trends and escaping.');
