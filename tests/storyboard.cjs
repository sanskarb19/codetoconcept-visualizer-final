const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {execFileSync}=require('node:child_process');
const cases=JSON.parse(execFileSync('python',['tests/storyboard_cases.py'],{encoding:'utf8',maxBuffer:5*1024*1024}));
const ctx={window:{}};
for(const path of ['learning','storyboard','tutor'])vm.runInNewContext(fs.readFileSync(`frontend/js/${path}.js`,'utf8'),ctx);
const {build,describe,expressionText}=ctx.window.Storyboard;
assert.equal(ctx.window.Storyboard.valueText({__type__:'none',value:null}),'None');
const steps=name=>build(cases[name].events,cases[name].statements,cases[name].source_code);
const add=steps('addition');
assert.equal(add.length,4,'four code instructions, rather than six raw trace events');
assert.equal(add[2].line,3);
assert.equal(add[2].before.x.value,10);
assert.equal(add[2].before.y.value,20);
assert.equal(add[2].before.total,undefined);
assert.equal(add[2].after.total.value,30);
assert.equal(expressionText(add[2].meta.expression,add[2].before),'10 + 20');
assert.equal(add[2].output,'');
assert.equal(add[3].output,'Total: 30\n');
assert.match(ctx.window.TutorFigures.instructionFigure(add[2]),/result-box/);
const rounds=steps('loop').filter(s=>s.meta.kind==='for');
assert.equal(rounds.length,4);
assert.deepEqual(Array.from(rounds,s=>s.decision),[true,true,true,false]);
assert.deepEqual(Array.from(rounds.slice(0,3),s=>s.after.i.value),[0,1,2]);
assert.equal(describe(rounds[3]).title,'The loop is finished');
assert.equal(steps('loop_last').filter(s=>s.meta.kind==='for').at(-1).decision,false);
assert.deepEqual(Array.from(steps('nested_loops').filter(s=>s.meta.kind==='for'&&s.line===2&&s.decision),s=>s.visit),[1,2,1,2]);
const branch=steps('decision').find(s=>s.meta.kind==='if');
assert.equal(branch.decision,false);
assert.equal(branch.next.line_number,5);
assert.match(describe(branch).title,/NO/);
assert.equal(expressionText(branch.meta.expression,branch.before),'78 ≥ 90');
const mutate=steps('mutation')[1];
assert.equal(mutate.before.items.value[1].value,1);
assert.equal(mutate.after.items.value[1].value,7);
const nested=steps('nested');
const enter=nested.find(s=>s.kind==='enter');
assert.equal(enter.after.x,undefined,'do not invent a result before the function returns');
assert.equal(enter.parameters.n.value,3);
const resume=nested.find(s=>s.kind==='resume');
assert.equal(resume.returnValue.value,6);
assert.equal(resume.after.x.value,6);
assert.equal(resume.before.x,undefined);
assert.ok(steps('recursion').some(s=>s.kind==='resume'&&s.returnValue.value===24));
assert.ok(steps('tree').some(s=>s.after.visited?.value.length>0));
assert.equal(steps('error').at(-1).exception.type,'ZeroDivisionError');
assert.ok(!steps('handled_error').some(s=>s.kind==='resume'&&s.event.function==='fail'),'an exceptional unwind is not a normal function return');
assert.match(describe(steps('error').at(-1)).title,/problem/);
const matrices=steps('matlab');
const multiply=matrices.find(s=>s.line===3);
const proof=ctx.window.TutorFigures.matrixProof(multiply,{proofCell:[1,1]});
assert.match(proof,/ROW 2 × COLUMN 2/);
assert.match(proof,/\(3 × 0\) \+ \(4 × 2\) = 8/);
const elementwise=ctx.window.TutorFigures.matrixProof(matrices.find(s=>s.line===4),{proofCell:[1,1]});
assert.match(elementwise,/MULTIPLY MATCHING CELLS/);
assert.match(elementwise,/\(4 × 2\) = 8/);
const powers=steps('matlab_powers');
assert.equal(powers[0].after.x.value,8);
assert.match(describe(powers[0]).why,/base to the exponent/);
assert.match(ctx.window.TutorFigures.instructionFigure(powers[0]),/2.*\^.*3/s);
assert.match(describe(powers.find(s=>s.line===3)).why,/matrix multiplication/);
assert.match(describe(powers.find(s=>s.line===4)).why,/each input cell/);
const evil={kind:'line',meta:{},changes:[{name:'<script>',before:undefined,after:{__type__:'str',value:'<script>alert(1)</script>'}}],before:{},after:{},next:{function:'main',line_number:2}};
assert.ok(!ctx.window.TutorFigures.instructionFigure(evil).includes('<script>'));
console.log('Passed: observed assignment results, loop rounds and exit, false branch, list mutations, delayed function results, recursion, shared tree state, exceptions, matrix cell calculations and HTML escaping.');
